// The two-bit level indicator that goes into the format information. NOT the order of
// `LEVELS` — L is 01 and M is 00, which is the kind of thing that silently produces a symbol
// readers reject as the wrong error level.
const LEVEL_BITS = { L: 0b01, M: 0b00, Q: 0b11, H: 0b10 };

// Alphanumeric mode's 45-character set, in its defined order. Index IS the value.
const ALNUM = '0123456789ABCDEFGHIJKLMNOPQRSTUVWXYZ $%*+-./:';

const MODE = {
  numeric: { indicator: 0b0001, counts: [10, 12, 14] },
  alnum: { indicator: 0b0010, counts: [9, 11, 13] },
  byte: { indicator: 0b0100, counts: [8, 16, 16] },
};

// Character-count indicator width depends on the version BAND, not the version.
function countBitsFor(mode, version) {
  const band = version <= 9 ? 0 : (version <= 26 ? 1 : 2);
  return MODE[mode].counts[band];
}

// ---------------------------------------------------------------------------------------
// mode selection — the cheapest mode the whole string fits in.
//
// Deliberately whole-string rather than segmented. Mixed-mode segmentation packs a little
// tighter, but it multiplies the ways this can be wrong, and the payloads here are short
// URLs and six-character codes. If a case ever needs it, the oracle will show it as a
// version too large rather than as an unreadable symbol.
export function chooseMode(text) {
  if (/^[0-9]*$/.test(text)) return 'numeric';
  for (const ch of text) if (!ALNUM.includes(ch)) return 'byte';
  return 'alnum';
}

const utf8 = (text) => Array.from(new TextEncoder().encode(text));

// How many BITS the payload itself occupies, excluding mode and count indicators.
function payloadBits(text, mode) {
  if (mode === 'numeric') {
    const groups = Math.floor(text.length / 3);
    const rest = text.length % 3;
    return groups * 10 + (rest === 0 ? 0 : rest === 1 ? 4 : 7);
  }
  if (mode === 'alnum') {
    return Math.floor(text.length / 2) * 11 + (text.length % 2) * 6;
  }
  return utf8(text).length * 8;
}

/** Total error-correction codewords at this version and level. */
export function ecCodewords(version, level) {
  return EC_PER_BLOCK[level][version - 1] * EC_BLOCKS[level][version - 1];
}

/** Data codewords available at this version and level. */
export function dataCodewords(version, level) {
  return TOTAL_CODEWORDS[version] - ecCodewords(version, level);
}

/**
 * Every codeword the block layout accounts for — data in every block, plus error correction
 * in every block. It must equal `TOTAL_CODEWORDS[version]` for all 160 combinations.
 *
 * Deliberately computed from `blockLayout` rather than from the tables directly, so it is a
 * real check on the DERIVED split (short blocks, long blocks, the remainder) rather than an
 * arithmetic identity that cannot fail. If a block table is ever mistyped, this is what says
 * so, and it says so for every version at once instead of only the ones a test encodes.
 */
export function tableSum(version, level) {
  const b = blockLayout(version, level);
  return b.shortCount * b.shortLen + b.longCount * b.longLen + b.blocks * b.ecPerBlock;
}

/**
 * How the data codewords divide into blocks.
 *
 * Blocks are not all the same size. The short ones come first, then the long ones, each
 * holding exactly one more codeword — and INTERLEAVING depends on that order, so this
 * returns them in it.
 */
export function blockLayout(version, level) {
  const blocks = EC_BLOCKS[level][version - 1];
  const data = dataCodewords(version, level);
  const shortLen = Math.floor(data / blocks);
  const longCount = data % blocks;
  const shortCount = blocks - longCount;
  return {
    blocks,
    ecPerBlock: EC_PER_BLOCK[level][version - 1],
    shortCount,
    shortLen,
    longCount,
    longLen: shortLen + 1,
    // The spec calls these group 1 and group 2, and so does every other implementation and
    // every reader of this code. Same numbers, the names the standard uses.
    blocksA: shortCount,
    dataA: shortLen,
    blocksB: longCount,
    dataB: shortLen + 1,
  };
}

/**
 * The smallest version that fits this text at this level.
 *
 * *** THE ARITHMETIC THAT WAS WRONG BEFORE. *** Everything is counted in BITS — mode
 * indicator, character count indicator, and payload — and rounded up to codewords ONCE, at
 * the end. The old code subtracted a constant number of codewords as a stand-in for the
 * header, which is both the wrong quantity and the wrong unit, and cost a whole version on a
 * payload that fitted exactly.
 *
 * The count indicator widens at versions 10 and 27, so a version can fail on header width
 * alone; the loop re-measures for every candidate rather than assuming the first one's width.
 */
export function chooseVersionFor(text, level, { min = 1, max = MAX_VERSION, mode = null } = {}) {
  const m = mode || chooseMode(text);
  const bits = payloadBits(text, m);
  for (let v = Math.max(1, min); v <= max; v++) {
    const need = 4 + countBitsFor(m, v) + bits;
    if (need <= dataCodewords(v, level) * 8) return { version: v, mode: m };
  }
  return null;
}

/**
 * Byte-mode version chooser, kept for callers that only know a length.
 * Correct now: header counted in bits, rounded once.
 */
export function chooseVersion(byteLength, level, { min = 1, max = MAX_VERSION } = {}) {
  for (let v = Math.max(1, min); v <= max; v++) {
    const need = 4 + countBitsFor('byte', v) + byteLength * 8;
    if (need <= dataCodewords(v, level) * 8) return v;
  }
  return null;
}

