// bitstream -> data codewords, then ECC, then interleave.

function encodeData(text, version, level, mode) {
  const bits = [];
  const push = (value, len) => { for (let i = len - 1; i >= 0; i--) bits.push((value >>> i) & 1); };

  push(MODE[mode].indicator, 4);

  if (mode === 'numeric') {
    push(text.length, countBitsFor('numeric', version));
    let i = 0;
    for (; i + 3 <= text.length; i += 3) push(Number(text.substr(i, 3)), 10);
    const rest = text.length - i;
    if (rest === 1) push(Number(text.substr(i, 1)), 4);
    else if (rest === 2) push(Number(text.substr(i, 2)), 7);
  } else if (mode === 'alnum') {
    push(text.length, countBitsFor('alnum', version));
    let i = 0;
    for (; i + 2 <= text.length; i += 2) {
      push(ALNUM.indexOf(text[i]) * 45 + ALNUM.indexOf(text[i + 1]), 11);
    }
    if (i < text.length) push(ALNUM.indexOf(text[i]), 6);
  } else {
    const bytes = utf8(text);
    push(bytes.length, countBitsFor('byte', version));
    for (const b of bytes) push(b, 8);
  }

  const capacity = dataCodewords(version, level) * 8;
  if (bits.length > capacity) throw new Error('qr: data does not fit the chosen version');

  // Terminator: up to four zero bits, and NOT more than the space left.
  for (let i = 0; i < 4 && bits.length < capacity; i++) bits.push(0);
  // Pad to a codeword boundary.
  while (bits.length % 8) bits.push(0);

  const words = [];
  for (let i = 0; i < bits.length; i += 8) {
    let v = 0;
    for (let j = 0; j < 8; j++) v = (v << 1) | bits[i + j];
    words.push(v);
  }
  // Then the two alternating pad codewords, forever, until the block is full.
  const pads = [0xec, 0x11];
  for (let i = 0; words.length < dataCodewords(version, level); i++) words.push(pads[i % 2]);
  return words;
}

function interleave(words, version, level) {
  const { blocks, ecPerBlock, shortCount, shortLen } = blockLayout(version, level);

  const dataBlocks = [];
  const ecBlocks = [];
  let at = 0;
  for (let b = 0; b < blocks; b++) {
    const len = b < shortCount ? shortLen : shortLen + 1;
    const block = words.slice(at, at + len);
    at += len;
    dataBlocks.push(block);
    ecBlocks.push(rsRemainder(block, ecPerBlock));
  }

  // Data codewords first, taking column `i` from every block that has one — the short blocks
  // simply run out first, which is why their contents had to come first above.
  const out = [];
  const maxData = Math.max(...dataBlocks.map((b) => b.length));
  for (let i = 0; i < maxData; i++) {
    for (const b of dataBlocks) if (i < b.length) out.push(b[i]);
  }
  // Then all the error-correction codewords, the same way. These are all the same length.
  for (let i = 0; i < ecPerBlock; i++) {
    for (const b of ecBlocks) out.push(b[i]);
  }
  return out;
}

